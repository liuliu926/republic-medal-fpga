"""Generate a small on-chip CJK glyph ROM for the first UI prototype."""

import json
from pathlib import Path
from typing import List
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "fpga" / "user_source" / "hdl_source" / "medal_font.vh"
FONT = ImageFont.truetype(r"C:\Windows\Fonts\msyh.ttc", 16)
PERSONS = [
    "于敏", "申纪兰", "孙家栋", "李延年", "张富清", "袁隆平", "黄旭华",
    "屠呦呦", "钟南山", "王永志", "王振义", "李振声", "黄宗德",
]
SECTIONS = ["生平", "主要贡献", "代表事迹", "互动问答"]
AUTO_LABEL = "自动轮播"
AUTO_PROMPT = "退出轮播请拨动SW3"
PILOT = json.loads((ROOT / "content" / "yu_min.json").read_text(encoding="utf-8"))
PILOT_PAGES = [entry["pages"] for entry in PILOT["sections"]]
PILOT_PAGES.append([PILOT["quiz"]["question"] + PILOT["quiz"]["choices"]])
ALL_PILOT_LINES = [line for section in PILOT_PAGES for page in section for line in page]
CHARS = "共和国勋章内容待添加" + "".join(PERSONS + SECTIONS + ALL_PILOT_LINES +
                                           [PILOT["quiz"]["feedback_correct"],
                                            PILOT["quiz"]["feedback_retry"],
                                            AUTO_LABEL, AUTO_PROMPT])
GLYPHS = list(dict.fromkeys(CHARS))


def table_function(name: str, selector_width: int, texts: List[str]) -> List[str]:
    result = [
        f"function [7:0] {name};",
        f"    input [{selector_width - 1}:0] selector;",
        "    input [2:0] char_index;",
        "    begin",
        f"        {name} = 8'd0;",
        "        case (selector)",
    ]
    for selector, word in enumerate(texts):
        result.append(f"            {selector_width}'d{selector}: begin")
        result.append("                case (char_index)")
        for offset, char in enumerate(word):
            result.append(f"                    3'd{offset}: {name} = 8'd{GLYPHS.index(char) + 1};")
        result += ["                    default: ;", "                endcase", "            end"]
    result += ["            default: ;", "        endcase", "    end", "endfunction", ""]
    return result


def glyph_rows(char: str) -> List[int]:
    image = Image.new("1", (16, 16), 0)
    draw = ImageDraw.Draw(image)
    width, height = draw.textsize(char, font=FONT)
    left = (16 - width) // 2
    top = (16 - height) // 2 - 2
    draw.text((left, top), char, font=FONT, fill=1)
    return [sum(int(image.getpixel((x, y))) << (15 - x) for x in range(16)) for y in range(16)]


lines = [
    "// Generated by medal_kiosk/tools/make_font.py; 16x16 MSB-left glyphs.",
    "function [15:0] medal_glyph_row;",
    "    input [7:0] glyph_id;",
    "    input [3:0] row;",
    "    begin",
    "        medal_glyph_row = 16'h0000;",
    "        case (glyph_id)",
]

for glyph_id, char in enumerate(GLYPHS, start=1):
    lines.append(f"            8'd{glyph_id}: begin // {char}")
    lines.append("                case (row)")
    for row_id, bits in enumerate(glyph_rows(char)):
        if bits:
            lines.append(f"                    4'd{row_id}: medal_glyph_row = 16'h{bits:04X};")
    lines.extend(["                    default: ;", "                endcase", "            end"])

lines.extend(["            default: ;", "        endcase", "    end", "endfunction", ""])
lines.extend(table_function("medal_person_char", 5, PERSONS))
lines.extend(table_function("medal_section_char", 2, SECTIONS))
lines.extend(table_function("medal_title_char", 1, ["共和国勋章", "内容待添加"]))
lines.extend(table_function("medal_feedback_char", 1,
                            [PILOT["quiz"]["feedback_correct"],
                             PILOT["quiz"]["feedback_retry"]]))

for function_name, label in [("medal_auto_char", AUTO_LABEL),
                             ("medal_prompt_char", AUTO_PROMPT)]:
    lines.extend([f"function [7:0] {function_name};",
                  "    input [3:0] char_index;", "    begin",
                  f"        {function_name} = 8'd0;", "        case (char_index)"])
    for char_id, char in enumerate(label):
        lines.append(f"            4'd{char_id}: {function_name} = 8'd{GLYPHS.index(char) + 1};")
    lines.extend(["            default: ;", "        endcase", "    end", "endfunction", ""])

lines.extend([
    "function [7:0] medal_pilot_char;",
    "    input [1:0] section;",
    "    input page;",
    "    input [1:0] line;",
    "    input [4:0] char_index;",
    "    begin",
    "        medal_pilot_char = 8'd0;",
    "        case ({section, page, line})",
])
for section_id, pages in enumerate(PILOT_PAGES):
    for page_id, page in enumerate(pages):
        for line_id, line_text in enumerate(page):
            if len(line_text) > 16:
                raise ValueError(f"Article line exceeds 16 glyphs: {line_text}")
            selector = (section_id << 3) | (page_id << 2) | line_id
            lines.append(f"            5'd{selector}: begin")
            lines.append("                case (char_index)")
            for char_id, char in enumerate(line_text):
                lines.append(f"                    5'd{char_id}: medal_pilot_char = 8'd{GLYPHS.index(char) + 1};")
            lines.extend(["                    default: ;", "                endcase", "            end"])
lines.extend(["            default: ;", "        endcase", "    end", "endfunction", ""])
OUT.write_text("\n".join(lines), encoding="utf-8")
print(f"Wrote {OUT} with {len(GLYPHS)} glyphs")
for glyph_id, char in enumerate(GLYPHS, start=1):
    print(f"{char}:{glyph_id}", end=" ")
print()
