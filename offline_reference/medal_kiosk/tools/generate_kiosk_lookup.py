"""Generate an isolated FPGA lookup table from the validated PC catalog.

Outputs FAT 8.3 directory-entry names (11 ASCII bytes, no period), metadata,
and explicit valid flags. It does not read the TF card or render any pixels.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'prepared_resource_catalog/catalog.json'
OUTPUT = ROOT / 'fpga/user_source_720p/hdl_source/kiosk_resource_lookup.v'


def short_name(name):
    stem, ext = name.split('.')
    assert 1 <= len(stem) <= 8 and ext == 'BMP'
    return f'{stem:<8}{ext}'


def main():
    c = json.loads(CATALOG.read_text(encoding='utf-8'))
    assert len(c['pages']) == 53 and len(c['portrait_order']) == 13
    v = ['''// Generated by tools/generate_kiosk_lookup.py. See MODULE6_RESOURCE_LOOKUP.md.
// Filenames use FAT short-name layout: eight name bytes followed by BMP.
// level: 0=home, 1=person intro, 2=article. section 0..2=life,
// contribution, deeds; section 3 is quiz and has no PPT background.
// layer_index is zero-based and distinct from the KEY4 reveal step.
module kiosk_resource_lookup(
    input wire [1:0] level,
    input wire [4:0] person_index,
    input wire [2:0] section_index,
    input wire [2:0] layer_index,
    input wire language_en,
    output reg page_valid,
    output reg quiz_page,
    output reg [5:0] slide_number,
    output reg [87:0] background_sfn,
    output reg portrait_valid,
    output reg [87:0] portrait_sfn,
    output reg [2:0] layer_count,
    output reg layer_valid,
    output reg [87:0] layer_sfn,
    output reg [10:0] layer_x, layer_width,
    output reg [9:0] layer_y, layer_height,
    output reg [2:0] reveal_step
);
always @* begin
    page_valid = 0; quiz_page = 0; slide_number = 0;
    if (level == 0) begin page_valid = 1; slide_number = 1; end
    else if (person_index < 13) begin
        if (level == 1) begin
            page_valid = 1; slide_number = 6'd2 + (person_index << 2);
        end else if (level == 2 && section_index < 3) begin
            page_valid = 1; slide_number = 6'd3 + (person_index << 2) + section_index;
        end else if (level == 2 && section_index == 3) quiz_page = 1;
    end
end
always @* begin
    background_sfn = 88'd0;
    layer_count = 0;
    case (slide_number)''']
    for p in c['pages']:
        n = p['slide']
        assert len(p['layers']) <= 7
        v.append(f'        6\'d{n}: begin background_sfn = "{short_name(p["background"])}"; layer_count = 3\'d{len(p["layers"])}; end')
    v.append('''        default: ;
    endcase
end
always @* begin
    portrait_valid = 0; portrait_sfn = 0;
    if (person_index < 13 && (level == 1 || level == 2)) begin
        portrait_valid = 1;
        case (person_index)''')
    for i, portrait in enumerate(c['portrait_order']):
        v.append(f'            5\'d{i}: portrait_sfn = "{short_name(portrait["file"])}";')
    v.append('''            default: begin portrait_valid = 0; portrait_sfn = 0; end
        endcase
    end
end
always @* begin
    layer_valid = 0; layer_sfn = 0; layer_x = 0; layer_y = 0;
    layer_width = 0; layer_height = 0; reveal_step = 0;
    case ({slide_number, layer_index})''')
    for p in c['pages']:
        for i, l in enumerate(p['layers']):
            assert l['key4_reveal_step'] <= 7
            z = short_name(l['files']['zh'])
            e = short_name(l['files']['en'])
            v.append(f'        {{6\'d{p["slide"]}, 3\'d{i}}}: begin layer_valid = 1; '
                     f'layer_sfn = language_en ? "{e}" : "{z}"; '
                     f'layer_x = 11\'d{l["x"]}; layer_y = 10\'d{l["y"]}; '
                     f'layer_width = 11\'d{l["width"]}; layer_height = 10\'d{l["height"]}; '
                     f'reveal_step = 3\'d{l["key4_reveal_step"]}; end')
    v.append('''        default: ;
    endcase
end
endmodule
''')
    OUTPUT.write_text('\n'.join(v), encoding='ascii')
    print(f'Generated {OUTPUT} with 53 pages, 13 portraits, 198 bilingual layer entries')

if __name__ == '__main__':
    main()
